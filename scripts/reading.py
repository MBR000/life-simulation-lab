"""Build the long-form reading layer: essays, stories and the library index.

Content lives in site/reading/*.html. Each file starts with one metadata
comment: <!--meta {...json...}-->. Called by scripts/publish_site.py.
"""

import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
READING = ROOT / "site" / "reading"
META_RE = re.compile(r"\A<!--meta (\{.*?\})-->\s*", re.S)
KINDS = {"essay": "文章", "story": "故事"}


def load_pieces():
    catalog = json.loads((READING / "order.json").read_text(encoding="utf-8"))
    pieces = []
    for slug in catalog["order"]:
        text = (READING / f"{slug}.html").read_text(encoding="utf-8")
        match = META_RE.match(text)
        if not match:
            raise ValueError(f"{slug}: missing meta comment")
        meta = json.loads(match.group(1))
        if meta.get("kind") not in KINDS:
            raise ValueError(f"{slug}: unknown kind")
        for key in ("title", "dek", "color", "sources", "card"):
            if key not in meta:
                raise ValueError(f"{slug}: missing {key}")
        meta["slug"] = slug
        meta["file"] = f"{slug}.html"
        meta["body"] = text[match.end():]
        pieces.append(meta)
    return pieces


def bar(active=""):
    return ('<nav class="site-bar" aria-label="站点导航">'
            '<a class="brand" href="index.html">人生模拟实验室</a>'
            f'<span class="crumb">{escape(active)}</span>'
            '<span class="nx"><a href="library.html">故事与文章</a>'
            '<a href="reports.html">全部报告</a></span></nav>')


def head(title, desc, color):
    return ('<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
            f'<title>{escape(title)} · 人生模拟实验室</title>\n'
            f'<meta name="description" content="{escape(desc)}">\n'
            f'<meta property="og:title" content="{escape(title)}">\n'
            f'<meta property="og:description" content="{escape(desc)}">\n'
            '<link rel="stylesheet" href="theme.css">\n<link rel="stylesheet" href="site.css">\n'
            '<link rel="stylesheet" href="reading.css">\n</head>\n'
            f'<body class="site read-page" style="--chapter:{color}">\n'
            '<!-- Generated by scripts/publish_site.py from site/reading/. -->\n'
            '<a class="skip-link" href="#content">跳到正文</a>\n')


FOOT = ('<footer class="read-foot"><span>人生模拟实验室 · 基于 1in8b v0.8.30 引擎的离线模拟，'
        '不是现实预测</span><span><a href="library.html">全部故事与文章</a> · '
        '<a href="index.html">首页</a> · <a href="https://github.com/MBR000/life-simulation-lab">GitHub</a></span></footer>\n'
        '</body>\n</html>\n')


def link_card(piece, eyebrow, cls=""):
    attr = f' class="{cls}"' if cls else ""
    return (f'<a{attr} href="{escape(piece["file"])}"><small>{escape(eyebrow)}</small>'
            f'<b>{escape(piece["title"])}</b></a>')


def page(piece, prev, nxt):
    kind = KINDS[piece["kind"]]
    sources = "".join(f'<li><a href="{escape(h)}">{escape(t)}</a></li>' for h, t in piece["sources"])
    nav = [link_card(prev, "← 上一篇") if prev else '<a href="library.html"><small>← 目录</small><b>全部故事与文章</b></a>',
           link_card(nxt, "下一篇 →", "r") if nxt else '<a class="r" href="reports.html"><small>继续深入 →</small><b>去看交互报告</b></a>']
    return (head(piece["title"], piece["dek"], piece["color"]) + bar(f'{kind} · {piece["title"]}')
            + '<main id="content"><header class="read-hero">'
            + f'<span class="kicker">{escape(kind)} · {escape(piece.get("tag", ""))}</span>'
            + f'<h1>{piece["title_html"] if "title_html" in piece else escape(piece["title"])}</h1>'
            + f'<p class="dek">{escape(piece["dek"])}</p>'
            + f'<div class="byline"><span>{escape(piece.get("reading", ""))}</span>'
            + '<span>数据：1in8b v0.8.30 离线批量模拟，2026-10-24 存档</span></div></header>\n'
            + f'<article class="prose {piece["kind"]}">\n{piece["body"]}\n</article>\n'
            + f'<aside class="sources"><h2>本文用到的数据</h2><ul>{sources}</ul></aside>\n'
            + f'<nav class="read-next" aria-label="继续阅读">{"".join(nav)}</nav></main>\n' + FOOT)


def card(piece, index):
    c = piece["card"]
    tone = f'style="--tone:{piece["color"]}"'
    if piece["kind"] == "essay":
        dark = " dark" if c.get("dark") else ""
        return (f'<a class="feature{dark}" href="{piece["file"]}" {tone} data-num="{index:02d}">'
                f'<span class="eyebrow">文章 · {escape(piece.get("tag", ""))}</span>'
                f'<h3>{escape(piece["title"])}</h3><p>{escape(c["blurb"])}</p>'
                f'<div class="big">{escape(c["big"])}<small>{escape(c["small"])}</small></div></a>')
    ages = "".join(f'<i style="--h:{max(4, round(a / 113 * 100))}%"></i>' for a in c.get("ages", []))
    return (f'<a class="story-card" href="{piece["file"]}" {tone}>'
            f'<span class="eyebrow">故事 · {escape(piece.get("tag", ""))}</span>'
            f'<h3>{escape(piece["title"])}</h3><p>{escape(c["blurb"])}</p>'
            f'<div class="ages" aria-hidden="true">{ages}</div><span class="go">读这个故事 →</span></a>')


def cards(pieces, kind):
    chosen = [p for p in pieces if p["kind"] == kind]
    return "\n".join(card(p, i) for i, p in enumerate(chosen, 1))


def library(pieces):
    return (head("故事与文章", "从 24.7 万次模拟人生里写出来的三篇文章和三个故事。", "#c0532d") + bar("故事与文章")
            + '<main class="hub" id="content"><header class="library-head"><span class="eyebrow">读物 · 3 篇文章 / 3 个故事</span>'
            + '<h1>二十四万次人生，<br>写成六篇读物</h1>'
            + '<p class="lede">交互报告回答“差多少”。这里换一种读法：文章把十五份报告里最重要的几个发现串起来，'
            + '故事则从原始人生纪录里挑出具体的人，逐条引用引擎写下的经历。</p></header>'
            + '<section class="shelf" aria-labelledby="essays"><div class="section-heading"><div><span class="eyebrow">文章</span>'
            + '<h2 id="essays">三个发现</h2></div><p>每篇约 6 分钟，数字全部来自已发布报告。</p></div>'
            + f'<div class="feature-grid">{cards(pieces, "essay")}</div></section>'
            + '<section class="shelf" aria-labelledby="stories"><div class="section-heading"><div><span class="eyebrow">故事</span>'
            + '<h2 id="stories">三组人生</h2></div><p>情节逐条来自引擎日志，没有补写。柱条是每个人的享年。</p></div>'
            + f'<div class="story-grid">{cards(pieces, "story")}</div></section>'
            + '<section class="method-note"><div><span class="eyebrow">写作约定</span><h2>故事怎么写成的</h2></div><div>'
            + '<p>每个故事都能用页面上标注的 seed 在 v0.8.30 引擎里复现。引号里的句子是引擎原文；叙述部分只做串联和归纳，不添加记录之外的情节。</p>'
            + '<p>文章里的数字取自各报告的汇总表。它们描述的是这个游戏引擎的规则与随机性，不是现实世界的统计结论。</p></div></section>'
            + '</main>\n' + FOOT)


def build():
    pieces = load_pieces()
    outputs = {ROOT / "library.html": library(pieces)}
    for i, piece in enumerate(pieces):
        prev = pieces[i - 1] if i else None
        nxt = pieces[i + 1] if i + 1 < len(pieces) else None
        outputs[ROOT / piece["file"]] = page(piece, prev, nxt)
    return pieces, outputs

